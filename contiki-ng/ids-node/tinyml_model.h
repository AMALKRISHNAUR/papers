/* Run inference */
static float tinyml_predict(const float *input, int input_size) {
  float hidden1[TINYML_HIDDEN_SIZE];
  float hidden2[8];
  float output;
  int i, j;
  
  /* Layer 1: Input -> Hidden1 */
  for(i = 0; i < TINYML_HIDDEN_SIZE; i++) {
    hidden1[i] = layer1_bias[i];
    for(j = 0; j < TINYML_NUM_FEATURES && j < input_size; j++) {
      hidden1[i] += input[j] * layer1_weights[j][i];
    }
    hidden1[i] = relu(hidden1[i]);
  }
  
  /* Layer 2: Hidden1 -> Hidden2 */
  for(i = 0; i < 8; i++) {
    hidden2[i] = layer2_bias[i];
    for(j = 0; j < TINYML_HIDDEN_SIZE; j++) {
      hidden2[i] += hidden1[j] * layer2_weights[j][i];
    }
    hidden2[i] = relu(hidden2[i]);
  }
  
  /* Layer 3: Hidden2 -> Output */
  output = layer3_bias;
  for(i = 0; i < 8; i++) {
    output += hidden2[i] * layer3_weights[i];
  }
  output = sigmoid(output);
  
  return output;
}

